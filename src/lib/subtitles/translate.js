/**
 * ============================================================================
 *  TRANSLATION — Google's translate endpoint
 * ============================================================================
 *
 *  The unit of translation here is the **sentence**, not the cue.
 *
 *  That distinction is the whole file. A subtitle cue is a *display* fragment:
 *  "People are always asking me" and "if I know Tyler Durden." are two cues
 *  because neither fits on one line at a readable size. They are one sentence.
 *
 *  Sending cues one per line translates each fragment in isolation, and a
 *  fragment has no verb to agree with, no object to follow it and no clause to
 *  close. The API does exactly what it is asked and returns one literal piece
 *  per line — which reads as word-for-word Kurdish, because it is. It is not a
 *  quality ceiling, it is the wrong input.
 *
 *  So cues are first grouped back into sentences, one sentence per line, and
 *  the translated sentence is then spread back across the cues it came from.
 *  Timings are never touched: a group's cues are contiguous, so redistributing
 *  text inside the group cannot drift the track.
 *
 *  The endpoint still translates *text*, not a list, so alignment is checked
 *  rather than assumed. A batch that cannot be lined up with what was sent is
 *  redone a sentence at a time — still whole sentences, so the fallback costs
 *  requests, never quality.
 * ============================================================================
 */

import site from '@config/site';
import { getKey } from '@/lib/settings';
import { SubtitleError } from './error';

const ENDPOINT = 'https://translate-pa.googleapis.com/v1/translate';

/**
 * How far a sentence may run before it is closed regardless of punctuation.
 *
 * Subtitles generated by speech recognition often carry no full stops at all,
 * and without a ceiling the whole file would collapse into one group. The cap
 * only ever merges cues that were going to be adjacent on screen anyway.
 */
const MAX_CUES_PER_SENTENCE = 4;
const MAX_CHARS_PER_SENTENCE = 200;

/** Ends a sentence, in either script. Trailing quotes/brackets still count. */
const SENTENCE_END = /[.?!…؟]["'»”’)\]]*$/;

/** Nothing but a bracketed sound cue: `[MUSIC]`, `(SIGHS)`. Not dialogue. */
const NON_PROSE = /^[\[(][^\])]*[\])]$/;

/** A leading dash marks a change of speaker; merging across one is wrong. */
const DIALOGUE_DASH = /^-/;

/** Cuts after sentence-final punctuation, keeping the mark with its sentence. */
const SENTENCE_BREAK = /[.?!…؟]+["'»”’)\]]*(?=\s|$)/g;

/**
 * The key, or null when the feature is not configured.
 *
 * Read through `getKey` alongside every other key rather than off the
 * environment directly, and specifically *not* listed in `EDITABLE` in
 * `src/lib/settings.js`. The two go together and only make sense together:
 * `getKey` resolves all three of its tiers for any name it is given, and
 * `EDITABLE` decides which names a viewer may write. So this key can come from
 * the build and from the environment, and can never be set from the interface —
 * which is the arrangement, rather than the key being special-cased in here.
 *
 * It has to come from the build in the desktop app, which has an empty
 * environment: without that tier the subtitle pipeline would have no key at all
 * and subtitles would never work on a machine nobody can debug.
 */
export function translateKey() {
  return getKey('TRANSLATE_API_KEY');
}

/**
 * Pulls the translated text out of a response, keeping its sentence structure.
 *
 * The exact JSON this endpoint returns is not documented, so rather than pin a
 * guess the known spellings are all accepted and the result is the list of
 * pieces it sent, in order. Which piece is which group is decided later, by
 * `alignGroups` — so this deliberately does not join them.
 *
 * @returns {string[]} translated fragments, in the order the API returned them
 */
function readPieces(data) {
  if (Array.isArray(data?.sentences)) {
    return data.sentences
      .map((sentence) => sentence?.trans ?? sentence?.translatedText ?? sentence?.text)
      .filter((piece) => typeof piece === 'string');
  }

  if (Array.isArray(data?.translations)) {
    return data.translations
      .map((entry) => entry?.translatedText ?? entry?.text ?? entry?.trans)
      .filter((piece) => typeof piece === 'string');
  }

  const single = data?.translation ?? data?.translatedText;
  if (typeof single === 'string') return [single];

  return [];
}

/**
 * Rebuilds cues into sentences.
 *
 * A group closes on sentence-final punctuation, on a cue that cannot be merged
 * (a sound effect, or a change of speaker), or on the size cap above. Every
 * group keeps the cues it was built from, which is what lets the translation be
 * handed back to them afterwards.
 *
 * @returns {{ cues: {startMs: number, endMs: number, text: string}[], text: string, sentences: string[] }[]}
 */
export function groupIntoSentences(cues) {
  const groups = [];
  let current = null;

  const close = () => {
    if (current) groups.push(current);
    current = null;
  };

  for (const cue of cues) {
    const standalone = NON_PROSE.test(cue.text) || DIALOGUE_DASH.test(cue.text);

    if (standalone) {
      close();
      groups.push({ cues: [cue], text: cue.text });
      continue;
    }

    if (!current) current = { cues: [], text: '' };
    current.cues.push(cue);
    current.text = current.text ? `${current.text} ${cue.text}` : cue.text;

    const full =
      current.cues.length >= MAX_CUES_PER_SENTENCE ||
      current.text.length >= MAX_CHARS_PER_SENTENCE;

    if (SENTENCE_END.test(current.text) || full) close();
  }

  close();

  // Each group carries the sentences it will actually be translated as. They
  // are what the request is built from and what the response is lined up
  // against, so the count is ours to know rather than the API's to report.
  return groups.map((group) => ({ ...group, sentences: splitSentences(group.text) }));
}

/**
 * Cuts text into sentences, keeping each mark with its sentence.
 *
 * A single cue can hold more than one sentence — subtitle files wrap and merge
 * lines freely, so "…with blasting gelatin. In 2 minutes…" arrives as one cue.
 * Splitting here rather than at the cue is what keeps every unit sent to the
 * translator a whole sentence.
 *
 * @returns {string[]}
 */
export function splitSentences(text) {
  const sentences = [];
  let at = 0;

  SENTENCE_BREAK.lastIndex = 0;
  for (let match = SENTENCE_BREAK.exec(text); match; match = SENTENCE_BREAK.exec(text)) {
    sentences.push(text.slice(at, match.index + match[0].length).trim());
    at = match.index + match[0].length;
  }

  // Whatever follows the last full stop is still a unit — a group closed by the
  // size cap ends mid-sentence, and trailing text must not be dropped.
  const tail = text.slice(at).trim();
  if (tail) sentences.push(tail);

  return sentences.filter(Boolean);
}

/**
 * Works out which translated text belongs to which group.
 *
 * The request is one line per *sentence*, so the expected response is one piece
 * per line, and the only thing to check is that the count came back. When it
 * does, the pieces are regrouped by the sentence counts we sent — a mapping
 * that holds by construction rather than by inference.
 *
 * This is deliberately strict. An earlier version tried to salvage a mismatch
 * by matching totals against punctuation guessed from the source, and it
 * silently shifted text between neighbouring groups: one sentence ended up
 * truncated while the next absorbed its tail. Counting what we actually sent is
 * the only claim worth making. Anything else falls back.
 *
 * @returns {string[]|null} one translation per group, or null if it did not line up
 */
function alignGroups(pieces, groups) {
  const expected = groups.map((group) => group.sentences.length);
  const total = expected.reduce((sum, count) => sum + count, 0);

  if (pieces.length !== total) return null;

  const texts = [];
  let at = 0;

  for (const count of expected) {
    texts.push(pieces.slice(at, at + count).join(' ').trim());
    at += count;
  }

  // An empty line where there was dialogue is a dropped line, not a
  // translation of one — treat the batch as unaligned rather than emit a cue
  // with no text.
  return texts.some((text) => !text) ? null : texts;
}

/**
 * Spreads one translated sentence back over the cues it was built from.
 *
 * Whole words only, in proportion to how much of the source sentence each cue
 * carried. The instruction to every step is the same: leave at least one word
 * for each cue still to come, so a long opening cue cannot swallow the sentence
 * and leave the screen blank underneath it.
 *
 * @returns {string[]} one string per cue, in order
 */
function spreadAcrossCues(text, cues) {
  if (cues.length < 2) return [text];

  const words = text.split(/\s+/).filter(Boolean);

  // Fewer words than cues: the sentence is shorter in Kurdish than the English
  // it replaced, so there is nothing to divide. Keep it whole on the first cue
  // and leave the rest empty — `toVtt` drops cues with no text — rather than
  // repeat a word to fill space.
  if (words.length < cues.length) return [text, ...Array(cues.length - 1).fill('')];

  const weights = cues.map((cue) => cue.text.length);
  const total = weights.reduce((sum, weight) => sum + weight, 0);

  const texts = [];
  let at = 0;

  for (let index = 0; index < cues.length - 1; index += 1) {
    const leftAfter = cues.length - index - 1;
    const share = Math.round((words.length * weights[index]) / total);

    const take = Math.max(1, Math.min(share, words.length - at - leftAfter));
    texts.push(words.slice(at, at + take).join(' '));
    at += take;
  }

  texts.push(words.slice(at).join(' '));
  return texts;
}

/** One request. `text` may hold many sentences, joined by newlines. */
async function requestTranslation(text, { source, target }) {
  const key = translateKey();
  if (!key) throw new SubtitleError('No translate API key configured', 'unavailable');

  const params = new URLSearchParams();
  params.set('params.client', 'gtx');
  params.set('query.source_language', source);
  params.set('query.target_language', target);
  params.set('query.display_language', 'en-US');
  params.set('query.text', text);
  params.set('key', key);
  // Repeated, not comma-joined: the API reads this as a list of data types.
  params.append('data_types', 'TRANSLATION');
  params.append('data_types', 'SENTENCE_SPLITS');
  params.append('data_types', 'BILINGUAL_DICTIONARY_FULL');

  let response;
  try {
    response = await fetch(`${ENDPOINT}?${params}`, { method: 'GET' });
  } catch (error) {
    throw new SubtitleError(error?.message ?? 'Could not reach the translator', 'translate-failed');
  }

  if (!response.ok) {
    if (response.status === 429) {
      throw new SubtitleError('Translation quota reached', 'limit', {
        status: 429,
        resetAt: response.headers.get('retry-after'),
      });
    }

    if (response.status === 401 || response.status === 403) {
      throw new SubtitleError('Translator rejected the API key', 'unavailable', {
        status: response.status,
      });
    }

    throw new SubtitleError(`Translator failed (${response.status})`, 'translate-failed', {
      status: response.status,
    });
  }

  const data = await response.json().catch(() => null);
  const pieces = readPieces(data);

  if (!pieces.length) {
    // The one failure mode that means *our* guess about the response shape was
    // wrong, rather than the API being unhappy. The body is logged so the next
    // person can fix `readPieces` in one line instead of guessing blind.
    if (process.env.NODE_ENV !== 'production') {
      console.warn(
        '[subtitles] unrecognised translation response:',
        JSON.stringify(data)?.slice(0, 500),
      );
    }
    throw new SubtitleError('Translator returned nothing usable', 'translate-failed');
  }

  return pieces;
}

/** Runs `worker` over `items`, `limit` at a time, preserving order. */
async function mapLimit(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;

  async function run() {
    while (next < items.length) {
      const index = next;
      next += 1;
      results[index] = await worker(items[index], index);
    }
  }

  const runners = Array.from({ length: Math.min(limit, items.length) }, run);
  await Promise.all(runners);

  return results;
}

/** Groups a batch of sentences into runs of at most `batchChars` characters. */
function batchGroups(groups, batchChars) {
  const batches = [];
  let current = [];
  let size = 0;

  for (const group of groups) {
    // A single sentence longer than the budget still gets its own batch rather
    // than being split — a sentence is the smallest unit we can translate.
    if (current.length && size + group.text.length > batchChars) {
      batches.push(current);
      current = [];
      size = 0;
    }
    current.push(group);
    size += group.text.length + 1;
  }

  if (current.length) batches.push(current);

  return batches;
}

/**
 * Translates cues, returning one translated string per cue in the same order.
 *
 * @param {{ startMs: number, endMs: number, text: string }[]} cues
 * @param {object} [options]
 * @param {(done: number, total: number) => void} [options.onProgress]
 * @returns {Promise<string[]>}
 * @throws {SubtitleError}
 */
export async function translateCues(cues, { onProgress } = {}) {
  const { batchChars, concurrency } = site.subtitles;
  const source = site.subtitles.sourceLanguage;
  const target = site.subtitles.target.code;

  const groups = groupIntoSentences(cues);
  const batches = batchGroups(groups, batchChars);
  let done = 0;

  const translated = await mapLimit(batches, concurrency, async (batch) => {
    // One line per sentence. A line break is what the endpoint treats as a unit
    // of translation, so this is what makes each unit a whole sentence.
    const joined = batch.flatMap((group) => group.sentences).join('\n');
    const pieces = await requestTranslation(joined, { source, target });

    let texts = alignGroups(pieces, batch);

    if (!texts) {
      // The response did not line up with what was sent. Re-do this batch one
      // group at a time: more requests, and the only way to be sure the words
      // land on the right cue. A group is still whole sentences, so this costs
      // time rather than quality.
      if (process.env.NODE_ENV !== 'production') {
        const sent = batch.reduce((count, group) => count + group.sentences.length, 0);
        console.warn(
          `[subtitles] batch of ${batch.length} sentences did not align (sent ${sent} lines, ${pieces.length} pieces back) — retrying one sentence at a time`,
        );
      }

      texts = await mapLimit(batch, concurrency, async (group) => {
        const single = await requestTranslation(group.text, { source, target });
        return single.join(' ').trim();
      });
    }

    done += batch.reduce((count, group) => count + group.cues.length, 0);
    onProgress?.(done, cues.length);

    return batch.map((group, index) => spreadAcrossCues(texts[index], group.cues));
  });

  return translated.flat(2);
}
